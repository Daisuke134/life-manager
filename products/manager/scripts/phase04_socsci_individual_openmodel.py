#!/usr/bin/env python3
"""A bounded real SocSci210 individual-response + public open-model comparison.

Processes source sample temporarily on Github Actions CPU. Source human
records, prompts, demographics and generated text are NEVER included in
report/output artifact, public git, or external inference requests.

This is not a reproduction of the 8B/14B Socrates researchers' estimator.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import sys
from tempfile import TemporaryDirectory
from time import monotonic
from urllib.request import Request,urlopen

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from scripts.socsci_split_audit import MAPPING_URL,EXPECTED_BYTES,EXPECTED_BLOB_SHA1,git_blob_sha
from scripts.phase04_socsci_empirical import DATA_REV,SQL_EXPR
from manager_core.phase04_socsci_empirical import BUCKETS
from manager_core.phase04_socsci_individual import evaluate_predictions,label_of_response

MODEL_ID="HuggingFaceTB/SmolLM2-135M-Instruct"
MODEL_REV="12fd25f77366fa6b3b4b768ec3050bf629380bac"
PER_STUDY=8
BATCH_SIZE=8

def mapping_exact():
    req=Request(MAPPING_URL,headers={"User-Agent":"Manager-Research-IndividualBench/1.0"})
    with urlopen(req,timeout=30) as stream:
        blob=stream.read(EXPECTED_BYTES+1)
    if len(blob)!=EXPECTED_BYTES or git_blob_sha(blob)!=EXPECTED_BLOB_SHA1:
        raise ValueError("pinned source study mapping has changed")
    mapping=json.loads(blob)
    if not (set(mapping)=={"seen","unseen"} and
            len(mapping["seen"])==170 and len(mapping["unseen"])==40 and
            not (set(mapping["seen"]) & set(mapping["unseen"]))):
        raise ValueError("study split integrity failure")
    return mapping


def evaluate():
    import duckdb
    import torch
    from transformers import AutoTokenizer,AutoModelForCausalLM
    from huggingface_hub import snapshot_download

    torch.set_num_threads(4)
    mapping=mapping_exact()
    t0=monotonic()
    # Ephemeral sandbox, not a shared/private production folder.
    with TemporaryDirectory(prefix="manager-socsci-openmodel-research-") as temp:
        data_dir=Path(temp)/"source"
        snapshot_download(
           repo_id="socratesft/SocSci210",repo_type="dataset",
           revision=DATA_REV,allow_patterns=["data/train-*.parquet"],
           local_dir=str(data_dir),max_workers=6)
        files=sorted((data_dir/"data").glob("train-*.parquet"))
        if len(files)!=17:raise ValueError("expected exactly 17 pinned Parquet files")
        conn=duckdb.connect(":memory:")
        conn.execute("SET threads=4")
        conn.execute("SET enable_progress_bar=false")
        conn.execute("SET memory_limit='3GB'")
        array="["+",".join("'"+str(p).replace("'","''") +"'" for p in files)+"]"
        # First pass only two non-personal columns; aggregate by study and
        # response code, matching the earlier 2.9M-row readback exactly.
        agg_sql=f"""SELECT study_id, {SQL_EXPR} AS bucket, COUNT(*)::INTEGER AS n
                       FROM read_parquet({array},union_by_name=true)
                       GROUP BY 1,2"""
        raw_agg=conn.execute(agg_sql).fetchall()
        aggregated=[(str(s),str(b),int(n)) for s,b,n in raw_agg]
        tr=set(mapping["seen"]);te=set(mapping["unseen"])
        train_counts=[v for v in aggregated if v[0] in tr]
        test_counts=[v for v in aggregated if v[0] in te]
        if (sum(x[2] for x in train_counts)!=2418748 or
            sum(x[2] for x in test_counts)!=482642):
            raise ValueError("source cohort totals differ from verified complete 17-shard benchmark")
        # Outcome-independent, predeclared sample: no response in hash/sort.
        # Raw person attributes are not selected; participant index is used
        # inside ROW_NUMBER only to disambiguate study-local event keys.
        markers=",".join(["?"]*len(te))
        sample_sql=f"""
          SELECT study_id,response,prompt FROM read_parquet({array},union_by_name=true)
          WHERE study_id IN ({markers})
          QUALIFY ROW_NUMBER() OVER (
            PARTITION BY study_id
            ORDER BY hash(study_id,participant,sample_id,task_num,condition_num,prompt),
                     sample_id,task_num,condition_num
          ) <= {PER_STUDY}
          ORDER BY study_id, hash(study_id,participant,sample_id,task_num,condition_num,prompt),
                   sample_id,task_num,condition_num"""
        actual=conn.execute(sample_sql,sorted(te)).fetchall()
        conn.close()
        if len(actual)!=len(te)*PER_STUDY:
            raise ValueError("insufficient clean test outcomes for every unseen study")
        # Input prompts exist only in this temporary process. No human
        # prompt, content, raw row, or output generated by the model
        # is printed, written to the artifact or sent to a model API.
        study_and_labels=[(str(s),label_of_response(int(y))) for s,y,_ in actual]
        prompts=[str(p) for _,_,p in actual]
        if any(not p for p in prompts):raise ValueError("empty study prompt")
        t_download=monotonic()-t0
        t_load=monotonic()
        tokenizer=AutoTokenizer.from_pretrained(MODEL_ID,revision=MODEL_REV,trust_remote_code=False)
        tokenizer.padding_side="left"
        tokenizer.truncation_side="left" # preserve question after persona profile
        if tokenizer.pad_token is None: tokenizer.pad_token=tokenizer.eos_token
        model=AutoModelForCausalLM.from_pretrained(
          MODEL_ID,revision=MODEL_REV,use_safetensors=True,trust_remote_code=False,torch_dtype=torch.float32
        ).eval()
        load_elapsed=monotonic()-t_load
        preds=[]
        inference_tokens=0
        input_tokens=0
        t_inf=monotonic()
        for start in range(0,len(prompts),BATCH_SIZE):
            batch=prompts[start:start+BATCH_SIZE]
            # The original source prompts are truncated for budget; prompt
            # format fixed ex ante and NOT adjusted using holdout outcomes.
            wrapped=[tokenizer.apply_chat_template([{
               "role":"user",
               "content":(p+"\n\n"
                  "For this fixed benchmark, output exactly ONE numeric response code "
                  "from 0 through 10, or OTHER if you cannot select such a code. "
                  "Do not write explanation. Response code:")
               }],tokenize=False,add_generation_prompt=True) for p in batch]
            tokens=tokenizer(wrapped,padding=True,truncation=True,
                             max_length=384,return_tensors="pt")
            input_tokens+=int(tokens["attention_mask"].sum().item())
            with torch.inference_mode():
                out=model.generate(**tokens,do_sample=False,max_new_tokens=5,
                                   pad_token_id=tokenizer.pad_token_id,
                                   eos_token_id=tokenizer.eos_token_id)
            cut=tokens["input_ids"].shape[1]
            for tokens_out in out:
                generated=tokens_out[cut:]
                inference_tokens+=len(generated)
                preds.append(tokenizer.decode(generated,skip_special_tokens=True).strip())
        seconds=monotonic()-t_inf
        report=evaluate_predictions(
          mapping,train_counts,study_and_labels,preds,
          requested_per_study=PER_STUDY,source_model=MODEL_ID,
          model_revision=MODEL_REV,elapsed_model_load_seconds=load_elapsed,
          elapsed_inference_seconds=seconds)
        report["source"]={
          "dataset":"socratesft/SocSci210",
          "revision":DATA_REV,
          "split_blob_sha1":EXPECTED_BLOB_SHA1,
          "original_paper":"https://aclanthology.org/2025.emnlp-main.1530/",
          "parquet_files":17,
          "all_train_rows_in_reference_distribution":2418748,
          "all_unseen_rows_for_sampling":482642,
          "full_dataset_projected_columns_for_training":["study_id","response"],
          "evaluation_projection":["study_id","response","prompt"],
          "dataset_download_and_aggregate_seconds":round(t_download,2)}
        report["model"]["input_tokens_total"]=input_tokens
        report["model"]["generated_tokens_total"]=inference_tokens
        report["model"]["sample_count"]=len(prompts)
        report["model"]["input_tokens_max"]=384
        report["model"]["generated_tokens_max"]=5
        report["model"]["model_license"]="Apache-2.0; original Socrates-trained 8B model carries additional Meta Llama license and is NOT this comparison model"
        report["evaluation"]["original_socrates_full_population_evaluation_reproduced"]=False
        report["evidence_boundary"]="Actual public human responses used for scoring; no outcome used to choose sample/model, no human causal effect validated."
        # Keep report free of participant traces.
        assert "prompts" not in report and "participants" not in report
        return report


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--output",type=Path,required=True)
    args=parser.parse_args()
    result=evaluate()
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(json.dumps(result,indent=2,sort_keys=True)+"\n",encoding="utf-8")
    print(json.dumps({
        "source":result["source"],
        "evaluation":result["evaluation"],
        "same_sample_scores":result["same_sample_scores"],
        "model":result["model"],
        "subgroup":result["subgroup"],
        "scientific_scope":result["scientific_scope"],
        "privacy":result["privacy"]},sort_keys=True))


if __name__=="__main__":
    main()
